/// The CSS class (and colour) of a knob page.
fn page_class(page: KnobPage) -> &'static str {
    match page {
        KnobPage::Sound => "sound",
        KnobPage::Setup => "setup",
        KnobPage::Macros => "rig",
    }
}

/// Distinct values in order, joined: "Output, Master".
fn dedup_join(items: &[String]) -> String {
    let mut seen: Vec<&str> = Vec::new();
    for item in items {
        if !seen.contains(&item.as_str()) {
            seen.push(item);
        }
    }
    seen.join(" or ")
}

/// Word-wrap to `width` characters.
fn wrap(text: &str, width: usize) -> Vec<String> {
    let mut lines = vec![String::new()];
    for word in text.split_whitespace() {
        let last = lines.last_mut().expect("one line");
        if last.is_empty() {
            last.push_str(word);
        } else if last.chars().count() + 1 + word.chars().count() <= width {
            last.push(' ');
            last.push_str(word);
        } else {
            lines.push(word.to_owned());
        }
    }
    lines
}

/// Escape text for HTML and SVG.
fn esc(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

