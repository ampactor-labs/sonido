//! The guide as a self-contained page: an annotated drawing of the pedal,
//! the knobs' three pages, the effect picker, the rig list, every jam effect
//! and factory rig, and the power-on gestures. One HTML file with inline SVG
//! and CSS, no external resources, light so it prints.

use std::fmt::Write as _;

use sonido_patch::Patch;
use sonido_patch::controls::{self, Footswitch, KnobPage, Mode, PowerOn, Press, Toggle};
use sonido_patch::pedal::{JAM_SLOTS, Topology};
use sonido_registry::{EffectRegistry, JAM_EFFECT_IDS};

use super::{KnobMode, jam_effect_knobs, knob_modes, rig_knobs, t2_place};

/// The guide page.
pub fn html_guide() -> String {
    let registry = EffectRegistry::new();
    let rigs = crate::factory_rigs();
    let modes = knob_modes(&registry, &rigs);

    let mut body = String::new();
    let b = &mut body;
    let _ = write!(
        b,
        "<header><h1>Sonido pedal</h1><p class=sub>How to play it. Drawn from the \
         code the pedal runs (link protocol {}), so it matches firmware built from \
         the same source.</p><div class=legend>",
        sonido_patch::link::PROTOCOL_VERSION
    );
    for m in &modes {
        let _ = write!(
            b,
            "<span class=\"chip {}\">{}</span>",
            page_class(m.page),
            esc(&m.when)
        );
    }
    b.push_str("</div></header>");

    b.push_str("<section class=face>");
    b.push_str(&face_svg(&modes));
    b.push_str("</section>");

    knob_pages(b, &modes);
    picker(b);
    rig_list(b, &rigs);
    effect_cards(b, &registry);
    rig_cards(b, &rigs, &modes);
    power_on(b);

    format!(
        "<!doctype html><html lang=en><head><meta charset=utf-8>\
         <meta name=viewport content=\"width=device-width,initial-scale=1\">\
         <title>Sonido pedal guide</title><style>{CSS}</style></head>\
         <body>{body}<footer>Generated by <code>sonido pedal controls</code> \
         from <code>sonido_patch::controls</code>, the knob maps and the factory \
         rigs.</footer></body></html>"
    )
}

// ── The pedal, drawn and annotated ──────────────────────────────────────────

/// Where the controls sit on the drawing (the Hothouse's layout).
const KNOB_X: [f32; 3] = [390.0, 500.0, 610.0];
const KNOB_Y: [f32; 2] = [190.0, 290.0];
const KNOB_R: f32 = 30.0;
const TOGGLE_Y: f32 = 400.0;
const LED_Y: f32 = 545.0;
const SWITCH_X: [f32; 2] = [400.0, 600.0];
const SWITCH_Y: f32 = 640.0;
const SWITCH_R: f32 = 32.0;
/// Callout columns.
const LEFT_X: f32 = 16.0;
const RIGHT_X: f32 = 694.0;
const BOX_W: f32 = 290.0;
/// Rough text metrics for wrapping (13 px system sans).
const CHARS_PER_LINE: usize = 40;
const LINE_H: f32 = 18.0;

/// One callout box: a title and lines, each line with an optional mode colour.
struct Callout {
    title: String,
    lines: Vec<(Option<KnobPage>, String)>,
}

impl Callout {
    fn new(title: impl Into<String>) -> Self {
        Self {
            title: title.into(),
            lines: Vec::new(),
        }
    }
    fn line(mut self, text: impl Into<String>) -> Self {
        self.lines.push((None, text.into()));
        self
    }
    fn mode(mut self, page: KnobPage, text: impl Into<String>) -> Self {
        self.lines.push((Some(page), text.into()));
        self
    }
    /// Draw it at (`x`, `y`); returns the SVG and the box's height.
    fn draw(&self, x: f32, y: f32) -> (String, f32) {
        let mut rows: Vec<(Option<KnobPage>, bool, String)> = Vec::new();
        for (page, text) in &self.lines {
            let indent = page.is_some();
            for (i, chunk) in wrap(text, CHARS_PER_LINE - usize::from(indent) * 2)
                .into_iter()
                .enumerate()
            {
                rows.push((*page, i == 0, chunk));
            }
        }
        let h = 34.0 + rows.len() as f32 * LINE_H + 8.0;
        let mut s = format!(
            "<rect x={x} y={y} width={BOX_W} height={h} rx=10 class=box />\
             <text x={} y={} class=ttl>{}</text>",
            x + 14.0,
            y + 24.0,
            esc(&self.title)
        );
        for (i, (page, first, text)) in rows.iter().enumerate() {
            let ty = y + 46.0 + i as f32 * LINE_H;
            let tx = x + 14.0 + if page.is_some() { 14.0 } else { 0.0 };
            if let (Some(page), true) = (page, *first) {
                let _ = write!(
                    s,
                    "<circle cx={} cy={} r=5 class=\"dot {}\" />",
                    x + 19.0,
                    ty - 4.5,
                    page_class(*page)
                );
            }
            let _ = write!(s, "<text x={tx} y={ty} class=txt>{}</text>", esc(text));
        }
        (s, h)
    }
}

/// A leader line from a callout to a control, with an optional elbow.
fn leader(from: (f32, f32), to: (f32, f32), elbow: Option<(f32, f32)>) -> String {
    let points = match elbow {
        Some((ex, ey)) => format!("{},{} {ex},{ey} {},{}", from.0, from.1, to.0, to.1),
        None => format!("{},{} {},{}", from.0, from.1, to.0, to.1),
    };
    format!(
        "<polyline points=\"{points}\" class=lead /><circle cx={} cy={} r=4 class=tip />",
        to.0, to.1
    )
}

fn face_svg(modes: &[KnobMode]) -> String {
    let mut s = String::from(
        "<svg viewBox=\"0 72 1000 718\" role=img \
         aria-label=\"The pedal with every control labelled\">\
         <defs><linearGradient id=metal x1=0 y1=0 x2=1 y2=1>\
         <stop offset=0 stop-color=\"#e4e4e2\"/><stop offset=1 stop-color=\"#b9b9b6\"/>\
         </linearGradient><radialGradient id=chrome cx=.4 cy=.35 r=.8>\
         <stop offset=0 stop-color=\"#fafafa\"/><stop offset=1 stop-color=\"#9a9a98\"/>\
         </radialGradient><radialGradient id=glow r=.5>\
         <stop offset=0 stop-color=\"#ff5b4a\" stop-opacity=.9/>\
         <stop offset=1 stop-color=\"#ff5b4a\" stop-opacity=0/></radialGradient></defs>",
    );

    // The enclosure, its jacks, and the controls.
    for jx in [420.0, 500.0, 580.0] {
        let _ = write!(
            s,
            "<rect x={} y=84 width=28 height=30 rx=4 class=jack />",
            jx - 14.0
        );
    }
    s.push_str("<rect x=330 y=110 width=340 height=640 rx=26 fill=\"url(#metal)\" class=body />");
    for (row, &ky) in KNOB_Y.iter().enumerate() {
        for (col, &kx) in KNOB_X.iter().enumerate() {
            let _ = write!(
                s,
                "<circle cx={kx} cy={ky} r={KNOB_R} class=knob />\
                 <line x1={kx} y1={} x2={kx} y2={} class=ptr />\
                 <text x={kx} y={} class=lbl>K{}</text>",
                ky - KNOB_R + 4.0,
                ky - KNOB_R + 16.0,
                ky + KNOB_R + 16.0,
                row * 3 + col + 1
            );
        }
    }
    for (i, &tx) in KNOB_X.iter().enumerate() {
        let _ = write!(
            s,
            "<circle cx={tx} cy={TOGGLE_Y} r=14 fill=\"url(#chrome)\" class=nut />\
             <rect x={} y={} width=6 height=20 rx=3 class=lever />\
             <text x={tx} y={} class=lbl>T{}</text>",
            tx - 3.0,
            TOGGLE_Y - 20.0,
            TOGGLE_Y + 32.0,
            i + 1
        );
    }
    for (i, &sx) in SWITCH_X.iter().enumerate() {
        let _ = write!(
            s,
            "<circle cx={sx} cy={LED_Y} r=16 fill=\"url(#glow)\" />\
             <circle cx={sx} cy={LED_Y} r=6 class=led />\
             <circle cx={sx} cy={SWITCH_Y} r={SWITCH_R} fill=\"url(#chrome)\" class=ring />\
             <circle cx={sx} cy={SWITCH_Y} r=20 class=stomp />\
             <text x={sx} y={} class=lbl>FS{}</text>",
            SWITCH_Y + SWITCH_R + 18.0,
            i + 1
        );
    }

    // Callouts. K3's job in every mode shows the "always a volume" rule.
    let k3: Vec<String> = modes.iter().map(|m| m.knobs[2].clone()).collect();
    let mut top = Callout::new("Top row · levels").line(format!(
        "K1 K2 K3. K3 (top right) is always a volume: {}.",
        dedup_join(&k3)
    ));
    top = top.line("Their jobs per mode are below.");
    let bottom = Callout::new("Bottom row · the sound").line(
        "K4 K5 K6: the effect's main controls, the jam's effect picks, or the rig's own sound.",
    );
    let pages: Vec<(KnobPage, String)> = modes
        .iter()
        .map(|m| (m.page, format!("{}: {}", m.when, m.what)))
        .collect();
    let mut legend = Callout::new("The knobs change jobs");
    for (page, text) in pages {
        legend = legend.mode(page, text);
    }

    let t1 = toggle_callout(
        Toggle::T1,
        "T1",
        |p| format!("slot {}", controls::slot(p) + 1),
        "in the jam: the slot the knobs edit",
    );
    let t3 = toggle_callout(
        Toggle::T3,
        "T3",
        |p| Topology::from_toggle(p).label().to_owned(),
        &format!("in the jam: how its {JAM_SLOTS} slots are wired"),
    );
    let glide = controls::footswitch(Footswitch::Fs2, Press::Tap, Mode::Morph).describe();
    let t2 = Callout::new("T2 · A / Morph / B")
        .line(format!(
            "▲ {} · ● {} · ▼ {}",
            Mode::A.label(),
            Mode::Morph.label(),
            Mode::B.label()
        ))
        .line(format!(
            "Up plays (and edits) A, down B; the middle sits between them, where FS2 taps {glide}."
        ));

    let (fs1, fs2) = (
        footswitch_callout(Footswitch::Fs1),
        footswitch_callout(Footswitch::Fs2),
    );
    let led1 = Callout::new("LED 1 · over FS1")
        .line(format!(
            "{} while on, {} when off",
            controls::led1(false, false).describe(),
            controls::led1(true, false).describe()
        ))
        .line(format!(
            "after a rig change: {}",
            controls::led1(false, true).describe()
        ));
    let mut led2 = Callout::new("LED 2 · over FS2");
    for (shows, places) in led2_groups() {
        led2 = led2.line(if places.is_empty() {
            format!("pedal off: {}", shows.describe())
        } else {
            format!("T2 {places}: {}", shows.describe())
        });
    }

    // Left column.
    let (svg, h) = top.draw(LEFT_X, 120.0);
    s.push_str(&svg);
    s.push_str(&leader(
        (LEFT_X + BOX_W, 120.0 + h / 2.0),
        (KNOB_X[0] - KNOB_R, KNOB_Y[0]),
        None,
    ));
    let y = 120.0 + h + 12.0;
    let (svg, h) = bottom.draw(LEFT_X, y);
    s.push_str(&svg);
    s.push_str(&leader(
        (LEFT_X + BOX_W, y + h / 2.0),
        (KNOB_X[0] - KNOB_R, KNOB_Y[1]),
        None,
    ));
    let y = (y + h + 12.0).max(TOGGLE_Y - 50.0);
    let (svg, h) = t1.draw(LEFT_X, y);
    s.push_str(&svg);
    s.push_str(&leader(
        (LEFT_X + BOX_W, y + h / 2.0),
        (KNOB_X[0] - 14.0, TOGGLE_Y),
        None,
    ));
    let y = y + h + 12.0;
    let (svg, h) = t2.draw(LEFT_X, y);
    s.push_str(&svg);
    let elbow_y = y + h / 2.0;
    s.push_str(&leader(
        (LEFT_X + BOX_W, elbow_y),
        (KNOB_X[1], TOGGLE_Y + 14.0),
        Some((KNOB_X[1], elbow_y)),
    ));
    let y = y + h + 12.0;
    let (svg, h) = led1.draw(LEFT_X, y);
    s.push_str(&svg);
    s.push_str(&leader(
        (LEFT_X + BOX_W, y + h / 2.0),
        (SWITCH_X[0] - 6.0, LED_Y),
        None,
    ));
    let y = (y + h + 12.0).max(SWITCH_Y - 30.0);
    let (svg, _) = fs1.draw(LEFT_X, y);
    s.push_str(&svg);
    s.push_str(&leader(
        (LEFT_X + BOX_W, y + 30.0),
        (SWITCH_X[0] - SWITCH_R, SWITCH_Y),
        None,
    ));

    // Right column.
    let (svg, h) = legend.draw(RIGHT_X, 120.0);
    s.push_str(&svg);
    s.push_str(&leader(
        (RIGHT_X, 120.0 + h / 2.0),
        (KNOB_X[2] + KNOB_R, KNOB_Y[0] + 40.0),
        None,
    ));
    let y = (120.0 + h + 12.0).max(TOGGLE_Y - 50.0);
    let (svg, h) = t3.draw(RIGHT_X, y);
    s.push_str(&svg);
    s.push_str(&leader(
        (RIGHT_X, y + h / 2.0),
        (KNOB_X[2] + 14.0, TOGGLE_Y),
        None,
    ));
    let y = (y + h + 12.0).max(LED_Y - 40.0);
    let (svg, h) = led2.draw(RIGHT_X, y);
    s.push_str(&svg);
    s.push_str(&leader(
        (RIGHT_X, y + h / 2.0),
        (SWITCH_X[1] + 6.0, LED_Y),
        None,
    ));
    let y = (y + h + 12.0).max(SWITCH_Y - 30.0);
    let (svg, _) = fs2.draw(RIGHT_X, y);
    s.push_str(&svg);
    s.push_str(&leader(
        (RIGHT_X, y + 30.0),
        (SWITCH_X[1] + SWITCH_R, SWITCH_Y),
        None,
    ));

    s.push_str("</svg>");
    s
}

/// A toggle's callout: its three positions, then what it does where.
fn toggle_callout(toggle: Toggle, name: &str, label: impl Fn(u8) -> String, jam: &str) -> Callout {
    let positions: Vec<String> = [(0u8, '▲'), (1, '●'), (2, '▼')]
        .iter()
        .map(|&(p, arrow)| format!("{arrow} {}", label(p)))
        .collect();
    let rig = if controls::toggle_active(toggle, false) {
        "in a rig: the same"
    } else {
        "in a rig: nothing (yet)"
    };
    Callout::new(name)
        .line(positions.join(" · "))
        .line(jam.to_owned())
        .line(rig)
}

/// A footswitch's callout: tap and hold, with any T2-middle variant.
fn footswitch_callout(fs: Footswitch) -> Callout {
    let name = if fs == Footswitch::Fs1 { "FS1" } else { "FS2" };
    let hold_s = f64::from(controls::HOLD_MS) / 1000.0;
    let tap = controls::footswitch(fs, Press::Tap, Mode::A).describe();
    let tap_morph = controls::footswitch(fs, Press::Tap, Mode::Morph).describe();
    let hold = controls::footswitch(fs, Press::Hold, Mode::A).describe();
    let mut c = Callout::new(format!("{name} · stomp")).line(format!("TAP: {tap}"));
    if tap_morph != tap {
        c = c.line(format!("T2 middle, TAP: {tap_morph}"));
    }
    c.line(format!("HOLD {hold_s:.1} s: {hold}"))
}

/// LED 2's states grouped by the T2 positions that share them, plus "off".
fn led2_groups() -> Vec<(controls::LedShows, String)> {
    let mut groups: Vec<(controls::LedShows, Vec<&str>)> = Vec::new();
    for p in [0u8, 1, 2] {
        let shows = controls::led2(false, Mode::from_toggle(p));
        let place = ["up", "middle", "down"][usize::from(p)];
        match groups.iter_mut().find(|(s, _)| *s == shows) {
            Some((_, places)) => places.push(place),
            None => groups.push((shows, vec![place])),
        }
    }
    let mut out: Vec<(controls::LedShows, String)> = groups
        .into_iter()
        .map(|(s, places)| (s, places.join("/")))
        .collect();
    out.push((controls::led2(true, Mode::A), String::new()));
    out
}

// ── The knobs' three pages ──────────────────────────────────────────────────

fn knob_pages(b: &mut String, modes: &[KnobMode]) {
    b.push_str(
        "<section><h2>What the knobs do</h2><p class=note>The six knobs have one \
         job per mode. Find the mode you're in, then read the knob where it sits.</p>\
         <div class=pages>",
    );
    for m in modes {
        let _ = write!(
            b,
            "<div class=\"card mode {}\"><div class=head>{}</div><div class=what>{}</div>",
            page_class(m.page),
            esc(&m.when),
            esc(m.what)
        );
        knob_grid(b, &m.knobs, &[]);
        b.push_str("</div>");
    }
    b.push_str("</div></section>");
}

/// A 2×3 knob face with a label under each knob; `muted` knobs are drawn
/// quieter (shared levels on rig cards).
fn knob_grid(b: &mut String, labels: &[String; 6], muted: &[usize]) {
    b.push_str("<div class=grid>");
    for (k, label) in labels.iter().enumerate() {
        let class = if muted.contains(&k) {
            "cell muted"
        } else {
            "cell"
        };
        let _ = write!(
            b,
            "<div class=\"{class}\"><span class=knobg></span><span class=k>K{}</span>\
             <span class=name>{}</span></div>",
            k + 1,
            esc(label)
        );
    }
    b.push_str("</div>");
}

// ── Picking an effect ───────────────────────────────────────────────────────

fn picker(b: &mut String) {
    let zones: Vec<&str> = std::iter::once("empty")
        .chain(JAM_EFFECT_IDS.iter().copied())
        .collect();
    let (cx, cy, r_label) = (300.0f32, 190.0f32, 128.0f32);
    let sweep = 300.0f32;
    let start = -150.0f32;
    let step = sweep / zones.len() as f32;
    let mut svg = String::from(
        "<svg class=dial viewBox=\"60 40 480 280\" role=img aria-label=\"The pick knob's zones\">",
    );
    // Travel arc and zone ticks.
    let point = |deg: f32, r: f32| {
        let a = deg.to_radians();
        (cx + r * a.sin(), cy - r * a.cos())
    };
    for i in 0..=zones.len() {
        let deg = start + step * i as f32;
        let (x1, y1) = point(deg, 66.0);
        let (x2, y2) = point(deg, 80.0);
        let _ = write!(svg, "<line x1={x1} y1={y1} x2={x2} y2={y2} class=tick />");
    }
    for (i, zone) in zones.iter().enumerate() {
        let deg = start + step * (i as f32 + 0.5);
        let (x, y) = point(deg, r_label);
        let (dx, dy) = point(deg, 92.0);
        let anchor = if x < cx - 20.0 {
            "end"
        } else if x > cx + 20.0 {
            "start"
        } else {
            "middle"
        };
        let class = if i == 0 { "zone empty" } else { "zone" };
        let _ = write!(
            svg,
            "<circle cx={dx} cy={dy} r=3 class=zdot />\
             <text x={x} y={} text-anchor={anchor} class=\"{class}\">{}</text>",
            y + 5.0,
            esc(zone)
        );
    }
    let _ = write!(
        svg,
        "<circle cx={cx} cy={cy} r=56 class=knob />\
         <line x1={cx} y1={} x2={cx} y2={} class=ptr />",
        cy - 52.0,
        cy - 32.0
    );
    svg.push_str("</svg>");
    let settle = f64::from(controls::PICK_SETTLE_MS) / 1000.0;
    let setup = controls::knob_page(true, Mode::Morph);
    let _ = write!(
        b,
        "<section><h2>Picking the jam's effects</h2><p class=note>On the setup page \
         (<span class=\"chip {}\">{}</span>) K4, K5 and K6 choose the effect in slots 1, \
         2 and 3, by where each knob points: fully left is empty. A pick loads once the \
         knob rests {settle:.1} s; one that would overload the pedal is refused and \
         LED 1 blinks.</p>{svg}</section>",
        page_class(setup),
        esc(&format!("In the jam, T2 {}", t2_place(1)))
    );
}

// ── The rig list ────────────────────────────────────────────────────────────

fn rig_list(b: &mut String, rigs: &[Patch]) {
    let back = controls::footswitch(Footswitch::Fs1, Press::Hold, Mode::A).describe();
    let next = controls::footswitch(Footswitch::Fs2, Press::Hold, Mode::A).describe();
    let _ = write!(
        b,
        "<section><h2>The rig list</h2><p class=note>Hold FS2 for the {next}, FS1 for \
         the {back}; the list wraps around. The pedal powers on into the rig it played \
         last.</p><div class=flow><span class=\"pill jam\">Jam</span><span class=arrow>→</span>\
         <span class=pill>Bank rigs 1–{} <small>(the filled slots)</small></span>",
        controls::BANK_SLOTS
    );
    for rig in rigs {
        let _ = write!(
            b,
            "<span class=arrow>→</span><span class=\"pill rig\">{}</span>",
            esc(&rig.name)
        );
    }
    b.push_str("<span class=arrow>↺</span></div></section>");
}

// ── Every jam effect and factory rig ────────────────────────────────────────

fn effect_cards(b: &mut String, registry: &EffectRegistry) {
    let sound = controls::knob_page(true, Mode::A);
    let _ = write!(
        b,
        "<section id=effects><h2>The jam's effects</h2><p class=note>With T2 up or \
         down (<span class=\"chip {}\">the slot's sound</span>), the knobs are the T1 \
         slot's effect: T2 up edits its A sound, down its B sound.</p><div class=cards>",
        page_class(sound)
    );
    for (id, knobs) in jam_effect_knobs(registry) {
        let _ = write!(
            b,
            "<div class=card id=\"fx-{}\"><div class=head>{}</div>",
            esc(&id),
            esc(&id)
        );
        knob_grid(b, &knobs, &[]);
        b.push_str("</div>");
    }
    b.push_str("</div></section>");
}

fn rig_cards(b: &mut String, rigs: &[Patch], modes: &[KnobMode]) {
    let shared = modes
        .iter()
        .find(|m| m.page == KnobPage::Macros)
        .map(|m| m.knobs.clone());
    b.push_str(
        "<section id=rigs><h2>The factory rigs</h2><p class=note>In a rig the knobs are \
         the rig's own. The bottom row is each rig's sound.</p><div class=cards>",
    );
    for rig in rigs {
        let knobs = rig_knobs(rig);
        let muted: Vec<usize> = (0..6)
            .filter(|&k| shared.as_ref().is_some_and(|s| s[k] == knobs[k]))
            .collect();
        let _ = write!(
            b,
            "<div class=\"card rigc\"><div class=head>{}</div>",
            esc(&rig.name)
        );
        knob_grid(b, &knobs, &muted);
        b.push_str("</div>");
    }
    b.push_str("</div></section>");
}

// ── Power-on ────────────────────────────────────────────────────────────────

fn power_on(b: &mut String) {
    let mut gestures: Vec<(PowerOn, Vec<&str>)> = Vec::new();
    for (fs1, fs2, held) in [
        (true, false, "Hold FS1"),
        (true, true, "Hold FS1 + FS2"),
        (false, false, "Hold neither"),
        (false, true, "Hold FS2 alone"),
    ] {
        let what = controls::power_on(fs1, fs2);
        match gestures.iter_mut().find(|(w, _)| *w == what) {
            Some((_, h)) => h.push(held),
            None => gestures.push((what, vec![held])),
        }
    }
    b.push_str(
        "<section><h2>Powering on</h2><p class=note>What to hold as you plug the power in.</p>\
         <div class=power>",
    );
    for (what, held) in gestures {
        let _ = write!(
            b,
            "<div class=card><div class=head>{}</div><div class=what>{}</div></div>",
            esc(&held.join(" or ")),
            esc(what.describe())
        );
    }
    b.push_str("</div></section>");
}

