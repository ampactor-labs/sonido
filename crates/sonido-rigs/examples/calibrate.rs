//! Measure every factory rig and regenerate `src/trims.rs`.
//!
//! ```sh
//! cargo run -p sonido-rigs --example calibrate --release
//! ```
//!
//! Each rig plays the reference guitar (`sonido_analysis::signals`) with
//! every knob at noon, halfway through its A/B morph; its master trim is set
//! so it plays at the dry guitar's loudness. The effects in it are already
//! level-calibrated (`sonido_core::level`); this matches the rig as a whole.

#[path = "../tests/support/measure.rs"]
mod measure;

use measure::{SR, rig_gain_db};
use sonido_analysis::signals::reference_guitar;
use sonido_registry::EffectRegistry;
use sonido_rigs::factory_rigs;

fn main() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/src/trims.rs");
    let registry = EffectRegistry::new();
    let input = reference_guitar(SR);
    let mut out = String::from(
        "//! Level-matching master trims for the factory rigs, in dB.\n\
         //!\n\
         //! Generated by `cargo run -p sonido-rigs --example calibrate --release`. Do\n\
         //! not edit by hand: the `factory` test fails when this table is out of date.\n",
    );
    for rig in factory_rigs() {
        let name = rig.name.to_uppercase().replace(' ', "_");
        let old = rig.globals.master_volume_db;
        let gain = rig_gain_db(&registry, &rig, 0.5, &input);
        let trim = old - gain;
        println!(
            "{:>18}: {gain:+6.2} dB  trim {old:+.2} -> {trim:+.2}",
            rig.name
        );
        out.push_str(&format!(
            "\n/// `{}` master volume at noon.\npub const {name}: f32 = {trim:.2};\n",
            rig.name
        ));
    }
    std::fs::write(path, out).expect("write trims.rs");
    println!("wrote {path}");
}
