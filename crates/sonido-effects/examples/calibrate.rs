//! Measure every effect against Sonido's level contract and regenerate
//! `src/calibration.rs` (see `sonido_core::level`).
//!
//! ```sh
//! cargo run -p sonido-effects --example calibrate --release
//! ```
//!
//! Each effect plays the reference guitar: fully wet when it has a mix
//! control (found from its descriptors), at its defaults otherwise. Its trim
//! is scaled by the measured loudness error (trims act after any
//! nonlinearity, so one run converges), and for a mix control the wet
//! signal's correlation with the dry input is measured for the blend. Run it
//! after changing a kernel's sound or defaults; the `level_contract` test
//! fails until you do.

use sonido_analysis::loudness::effect_gain_db;
use sonido_analysis::signals::reference_guitar;
use sonido_core::{Effect, EffectWithParams};
use sonido_registry::{EFFECT_UIDS, EffectRegistry};

const SR: f32 = 48_000.0;

/// Utilities with nothing to match: the looper's wet signal is its (empty)
/// loop, and the tuner passes its input through.
const UNCALIBRATED: &[&str] = &["looper", "tuner"];

fn main() {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/src/calibration.rs");
    let current = std::fs::read_to_string(path).expect("read calibration.rs");
    let registry = EffectRegistry::new();
    let input = reference_guitar(SR);
    let mut ids: Vec<&str> = EFFECT_UIDS.iter().map(|(id, _)| *id).collect();
    ids.sort_unstable();

    let mut out = String::from(
        "//! Measured level calibration for every kernel (see `sonido_core::level`).\n\
         //!\n\
         //! Generated by `cargo run -p sonido-effects --example calibrate`. Do not edit\n\
         //! by hand: the `level_contract` test fails when this table is out of date.\n\
         \n\
         use sonido_core::level::Level;\n",
    );
    for id in ids {
        let name = id.to_uppercase();
        let old = old_trim(&current, &name);
        let fresh = |mix: Option<usize>| {
            let mut effect = registry.create(id, SR).expect("registered effect");
            if let Some(i) = mix {
                effect.effect_set_param(i, 100.0);
            }
            effect.reset();
            effect
        };
        let probe = fresh(None);
        let mix = (0..probe.effect_param_count()).find(|&i| {
            probe
                .effect_param_info(i)
                .is_some_and(|d| d.matches_key("mix"))
        });

        let (trim, rho, note) = if UNCALIBRATED.contains(&id) {
            (1.0, None, String::from("not calibrated (a utility)"))
        } else {
            let gain = effect_gain_db(fresh(mix).as_mut(), &input, SR);
            let trim = old * 10f32.powf(-gain / 20.0);
            let rho = mix.map(|_| correlation(fresh(mix).as_mut(), &input));
            let state = if mix.is_some() {
                "fully wet"
            } else {
                "at defaults"
            };
            println!("{id:>18}: {gain:+6.2} dB {state}  trim {old:.4} -> {trim:.4}  rho {rho:?}");
            (
                trim,
                rho,
                format!("{:+.1} dB, {state}", 20.0 * trim.log10()),
            )
        };
        let rho = rho.map_or(String::from("None"), |r| format!("Some({r:.3})"));
        out.push_str(&format!(
            "\n/// `{id}`: {note}.\npub const {name}: Level = Level {{\n    trim: {trim:.4},\n    mix_correlation: {rho},\n}};\n"
        ));
    }
    std::fs::write(path, out).expect("write calibration.rs");
    println!("wrote {path}");
}

/// The trim currently in the table for `name` (1.0 if absent).
fn old_trim(table: &str, name: &str) -> f32 {
    let start = format!("pub const {name}: Level = Level {{");
    table
        .split(&start)
        .nth(1)
        .and_then(|rest| rest.split("trim: ").nth(1))
        .and_then(|v| v.split(',').next())
        .and_then(|v| v.trim().parse().ok())
        .unwrap_or(1.0)
}

/// Zero-lag correlation of the effect's (fully wet) output with its input.
fn correlation(effect: &mut (dyn EffectWithParams + Send), input: &[f32]) -> f32 {
    let (mut xy, mut xx, mut yy) = (0.0f64, 0.0f64, 0.0f64);
    for chunk in input.chunks(32) {
        let (mut l, mut r) = (chunk.to_vec(), chunk.to_vec());
        Effect::process_block_stereo_inplace(effect, &mut l, &mut r);
        for ((x, a), b) in chunk.iter().zip(&l).zip(&r) {
            let (x, y) = (f64::from(*x), 0.5 * f64::from(a + b));
            xy += x * y;
            xx += x * x;
            yy += y * y;
        }
    }
    (xy / (xx * yy).sqrt().max(1e-30)) as f32
}
